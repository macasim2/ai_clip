"""Subtitle generation from Whisper word timings.

ASS is the primary format: it is burned into the final 1080x1920 vertical
render, so the real pixel geometry (script resolution, font size, margins)
must live *inside* the ASS file instead of relying on an SRT ``force_style``
override that is scaled from the SRT default canvas (384x288).

The SRT copy is kept as a plain, human-readable review artifact.
"""
from __future__ import annotations

import math
import re
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

from .logging_setup import get_logger
from .models import TranscriptWord

log = get_logger(__name__)

# --------------------------------------------------------------------- layout
# ASS script resolution == final video resolution: 1 font unit == 1 pixel.
PLAY_RES_X = 1080
PLAY_RES_Y = 1920
WRAP_STYLE = 2
ALIGNMENT_BOTTOM_CENTER = 2
MARGIN_LR = 60
DEFAULT_MARGIN_V = 140
DEFAULT_FONT = "Arial"
DEFAULT_FONT_SIZE = 64
OUTLINE_WIDTH = 3
SHADOW_DEPTH = 1

# --------------------------------------------------------------------- limits
DEFAULT_MAX_WORDS = 4
DEFAULT_MAX_CHARS = 24
DEFAULT_MAX_DURATION = 4.0
MAX_LINES = 2
SENTENCE_END = ".!?…"
CLOSING_CHARS = "\"'”’»)]}"

# --------------------------------------------------------------------- timing
CENTI = 100
GAP_SPLIT = 0.6          # speech pause (s) that starts a new cue
MIN_CUE_CENTI = 35       # 0.35 s minimum on-screen time
CUE_GAP_CENTI = 2        # 0.02 s gap between neighbouring cues
RESERVE_CENTI = MIN_CUE_CENTI + CUE_GAP_CENTI

# --------------------------------------------------------------------- accent
ACCENT_COLOUR = "&H00D7FF&"   # gold, ASS inline override value (BGR)
PRIMARY_INLINE = "&HFFFFFF&"  # restore white after the accent word
ASS_PRIMARY = "&H00FFFFFF"    # ASS style colour (AABBGGRR)

# Approximate average glyph advance of a bold Arial-like font, in em units
# (measured with libass: bold Arial 64px averages ~0.60 em per character, and
# the outline adds a few pixels on both sides).  Used only as an upper bound so
# a very large font / high subtitle_max_chars can never spill out of the
# 1080 px frame; cfg.subtitle_max_chars normally stays the tighter limit.
_GLYPH_ADVANCE = 0.62

_ASS_HEADER = """[Script Info]
; Generated by AI Clip Studio - do not edit by hand
Title: AI Clip Studio subtitles
ScriptType: v4.00+
PlayResX: {width}
PlayResY: {height}
WrapStyle: {wrap_style}
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{font},{size},{primary},&H000000FF,&H00000000,&H80000000,1,0,0,0,100,100,0,0,1,{outline},{shadow},{alignment},{margin_l},{margin_r},{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

_CONTROL_CHARS = re.compile(r"[\x00-\x1f\x7f]")
_ASS_BRACES = re.compile(r"[{}]")  # braces start/end ASS override blocks
_WHITESPACE = re.compile(r"\s+")


# ------------------------------------------------------------------ cfg utils
def _cfg_get(cfg, name: str, default):
    value = getattr(cfg, name, None)
    return default if value is None else value


def _as_int(value, default: int, minimum: int = 0) -> int:
    try:
        number = int(value)
    except (TypeError, ValueError, OverflowError):
        return default
    return number if number >= minimum else default


def _as_float(value, default: float, minimum: float = 0.0) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError, OverflowError):
        return default
    if not math.isfinite(number) or number < minimum:
        return default
    return number


def _font_name(cfg) -> str:
    value = _cfg_get(cfg, "subtitle_font", DEFAULT_FONT)
    name = _CONTROL_CHARS.sub(" ", str(value or DEFAULT_FONT))
    # Comma would break the comma-separated Style line.
    name = name.replace(",", " ").strip()
    return name or DEFAULT_FONT


def _font_size(cfg) -> int:
    return _as_int(_cfg_get(cfg, "subtitle_font_size", DEFAULT_FONT_SIZE),
                   DEFAULT_FONT_SIZE, 1)


def _margin_v(cfg) -> int:
    return _as_int(_cfg_get(cfg, "subtitle_margin_v", DEFAULT_MARGIN_V),
                   DEFAULT_MARGIN_V, 0)


def _play_res_x(cfg) -> int:
    return _as_int(_cfg_get(cfg, "video_width", PLAY_RES_X), PLAY_RES_X, 16)


def _play_res_y(cfg) -> int:
    return _as_int(_cfg_get(cfg, "video_height", PLAY_RES_Y), PLAY_RES_Y, 16)


def _accent_enabled(cfg) -> bool:
    return str(_cfg_get(cfg, "subtitle_style", "normal") or "").strip().lower() == "accent"


def _max_words(cfg) -> int:
    return _as_int(_cfg_get(cfg, "subtitle_max_words", DEFAULT_MAX_WORDS),
                   DEFAULT_MAX_WORDS, 1)


def _max_duration(cfg) -> float:
    return _as_float(_cfg_get(cfg, "subtitle_max_duration", DEFAULT_MAX_DURATION),
                     DEFAULT_MAX_DURATION, 0.1)


def _line_char_limit(cfg) -> int:
    """Per-line character budget: config value, capped by frame width."""
    max_chars = _as_int(_cfg_get(cfg, "subtitle_max_chars", DEFAULT_MAX_CHARS),
                        DEFAULT_MAX_CHARS, 1)
    usable_px = max(1, _play_res_x(cfg) - 2 * MARGIN_LR)
    width_cap = int(usable_px / max(1.0, _font_size(cfg) * _GLYPH_ADVANCE))
    return max(1, min(max_chars, width_cap))


# ----------------------------------------------------------------- word text
def _clean_word(raw: object) -> str:
    """Plain text of a transcript word, safe for both ASS and SRT."""
    text = str(raw if raw is not None else "")
    text = _CONTROL_CHARS.sub(" ", text)
    text = _ASS_BRACES.sub("", text)
    return _WHITESPACE.sub(" ", text).strip()


def _cue_words_text(cue: Sequence[TranscriptWord]) -> List[str]:
    words: List[str] = []
    for item in cue:
        text = _clean_word(getattr(item, "word", ""))
        if text:
            words.append(text)
    return words


def _ends_sentence(word: str) -> bool:
    """True when the word closes a sentence, ignoring trailing quotes/brackets."""
    core = word.rstrip(CLOSING_CHARS)
    return bool(core) and core[-1] in SENTENCE_END


def _wrap_words(words: Sequence[str], max_chars: int) -> List[List[str]]:
    """Greedy word wrap.

    Words are never split: a single word longer than ``max_chars`` gets a line
    of its own (and therefore may exceed the limit, as required).
    """
    lines: List[List[str]] = []
    current: List[str] = []
    current_len = 0
    for word in words:
        if not word:
            continue
        if current and current_len + 1 + len(word) > max_chars:
            lines.append(current)
            current, current_len = [], 0
        current_len += len(word) + (1 if current else 0)
        current.append(word)
    if current:
        lines.append(current)
    return lines


# ----------------------------------------------------------------- grouping
def _group_cues(words: List[TranscriptWord], start_off: float, end_off: float,
                max_words: int, max_chars: int, max_duration: float,
                gap_split: float = GAP_SPLIT) -> List[List[TranscriptWord]]:
    """Split words into readable cue-sized groups.

    A group is closed before a word when: adding it would exceed max_words,
    the silence before it is longer than ``gap_split``, the cue would last
    longer than ``max_duration``, or the text would no longer fit into two
    wrapped lines.  A group is also closed *after* a word that ends a
    sentence.
    """
    groups: List[List[TranscriptWord]] = []
    current: List[TranscriptWord] = []
    for word in words:
        text = _clean_word(getattr(word, "word", ""))
        if not text:
            continue
        if word.end <= start_off or word.start >= end_off:
            continue
        if current:
            previous = current[-1]
            gap = float(word.start) - float(previous.end)
            span = (min(float(word.end), end_off)
                    - max(float(current[0].start), start_off))
            pending = _cue_words_text(current) + [text]
            split = (
                len(current) >= max_words
                or gap > gap_split
                or span > max_duration
                or len(_wrap_words(pending, max_chars)) > MAX_LINES
            )
            if split:
                groups.append(current)
                current = []
        current.append(word)
        if _ends_sentence(text):
            groups.append(current)
            current = []
    if current:
        groups.append(current)
    return groups


def _group(words: List[TranscriptWord], start_off: float, end_off: float,
           max_words: int, max_chars: int,
           gap_split: float = GAP_SPLIT) -> List[List[TranscriptWord]]:
    """Backward-compatible grouping helper (no cue-duration limit)."""
    return _group_cues(words, start_off, end_off, max_words, max_chars,
                       float("inf"), gap_split)


# ------------------------------------------------------------------- timing
def _window_duration(start_off: float, end_off: float) -> float:
    return max(0.0, float(end_off) - float(start_off))


def _duration_centi(duration: float) -> int:
    # Floor so a written timestamp can never exceed the real clip duration.
    return max(1, int(math.floor(duration * CENTI + 1e-9)))


def _raw_bounds(cue: Sequence[TranscriptWord], start_off: float,
                duration: float, duration_centi: int) -> Tuple[int, int]:
    """Cue bounds in centiseconds relative to the window, clamped to [0, d]."""
    start = min(max(float(cue[0].start) - start_off, 0.0), duration)
    end = min(max(float(cue[-1].end) - start_off, 0.0), duration)
    start_centi = min(max(int(round(start * CENTI)), 0), duration_centi)
    end_centi = min(max(int(round(end * CENTI)), 0), duration_centi)
    return start_centi, end_centi


def _normalize_times(raws: Sequence[Tuple[int, int]],
                     duration_centi: int) -> List[Optional[Tuple[int, int]]]:
    """Enforce display minimum, window clamping and non-overlap in centiseconds.

    ``None`` marks a cue that cannot be placed without overlapping the previous
    one (only possible when the window is far too short for all cues).
    """
    cues: List[Optional[Tuple[int, int]]] = []
    prev_end: Optional[int] = None
    total = len(raws)
    for index, (start_centi, end_centi) in enumerate(raws):
        remaining = total - 1 - index
        # Keep room for every later cue (minimum display + gap).
        reserve = min(remaining * RESERVE_CENTI, max(0, duration_centi - 1))
        end_limit = duration_centi - reserve
        if prev_end is not None:
            end_limit = max(end_limit, prev_end + CUE_GAP_CENTI + 1)
            end_limit = min(end_limit, duration_centi)
        floor = 0 if prev_end is None else prev_end + CUE_GAP_CENTI
        if floor >= duration_centi:
            log.warning("subtitle cue %d dropped: no room left in window",
                        index + 1)
            cues.append(None)
            continue

        start = max(start_centi, floor)
        if start >= end_limit:
            start = max(floor, end_limit - 1)
            if start >= end_limit:
                log.warning("subtitle cue %d dropped: no room left in window",
                            index + 1)
                cues.append(None)
                continue
        end = min(max(end_centi, start + 1), end_limit)
        if end - start < MIN_CUE_CENTI:
            end = min(start + MIN_CUE_CENTI, end_limit)
            if end - start < MIN_CUE_CENTI:
                # Shift the start earlier rather than shorten the display;
                # ``floor`` keeps the 0.02 s gap to the previous cue.
                start = max(floor, end - MIN_CUE_CENTI)
        if end <= start:
            log.warning("subtitle cue %d dropped: zero display time", index + 1)
            cues.append(None)
            continue
        cues.append((start, end))
        prev_end = end
    return cues


def _build_cue_plan(words: List[TranscriptWord], start_off: float,
                    end_off: float, cfg) -> List[Tuple[int, int, List[List[str]]]]:
    """Return (start_cs, end_cs, wrapped lines) for every cue in the window."""
    duration = _window_duration(start_off, end_off)
    if duration <= 0 or not words:
        return []
    duration_centi = _duration_centi(duration)
    max_chars = _line_char_limit(cfg)
    groups = _group_cues(words, start_off, end_off, _max_words(cfg),
                         max_chars, _max_duration(cfg))
    raws: List[Tuple[int, int]] = []
    lines: List[List[List[str]]] = []
    for group in groups:
        raws.append(_raw_bounds(group, start_off, duration, duration_centi))
        lines.append(_wrap_words(_cue_words_text(group), max_chars))

    plan: List[Tuple[int, int, List[List[str]]]] = []
    for times, cue_lines in zip(_normalize_times(raws, duration_centi), lines):
        if times is None or not cue_lines:
            continue
        plan.append((times[0], times[1], cue_lines))
    return plan


# ------------------------------------------------------------------ render
def _is_important_word(word: str) -> bool:
    if "!" in word:
        return True
    letters = "".join(ch for ch in word if ch.isalpha())
    if len(letters) >= 3 and letters.isupper():
        return True
    return any(ch.isdigit() for ch in word)


def _pick_accent_index(words: Sequence[str]) -> Optional[int]:
    """One highlighted word per cue: marker word (``!``, CAPS, digits) else longest."""
    if not words:
        return None
    important = [i for i, word in enumerate(words) if _is_important_word(word)]
    pool = important or list(range(len(words)))
    return max(pool, key=lambda i: (len(words[i]), -i))


def _render_ass_text(lines: Sequence[Sequence[str]],
                     accent_index: Optional[int]) -> str:
    """Join wrapped lines with ASS ``\\N`` and apply the accent override."""
    rendered_lines: List[str] = []
    flat_index = 0
    for line in lines:
        parts: List[str] = []
        for word in line:
            if flat_index == accent_index:
                parts.append(f"{{\\c{ACCENT_COLOUR}}}{word}"
                             f"{{\\c{PRIMARY_INLINE}}}")
            else:
                parts.append(word)
            flat_index += 1
        rendered_lines.append(" ".join(parts))
    return "\\N".join(rendered_lines)


def _ass_timestamp(centi: int) -> str:
    centi = max(0, int(centi))
    hours, rest = divmod(centi, 360000)
    minutes, rest = divmod(rest, 6000)
    seconds, fraction = divmod(rest, CENTI)
    return f"{hours}:{minutes:02d}:{seconds:02d}.{fraction:02d}"


def _ass_header(cfg) -> str:
    return _ASS_HEADER.format(
        width=_play_res_x(cfg),
        height=_play_res_y(cfg),
        wrap_style=WRAP_STYLE,
        font=_font_name(cfg),
        size=_font_size(cfg),
        primary=ASS_PRIMARY,
        outline=OUTLINE_WIDTH,
        shadow=SHADOW_DEPTH,
        alignment=ALIGNMENT_BOTTOM_CENTER,
        margin_l=MARGIN_LR,
        margin_r=MARGIN_LR,
        margin_v=_margin_v(cfg),
    )


# ---------------------------------------------------------------- public API
def _ts(t: float) -> str:
    """SRT timestamp (HH:MM:SS.mmm, as in the previous implementation)."""
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = t % 60
    return f"{h:02d}:{m:02d}:{s:06.3f}"


def build_ass(words: List[TranscriptWord], start_off: float, end_off: float,
              cfg) -> str:
    """Build a complete ASS subtitle file for the 1080x1920 render."""
    accents = _accent_enabled(cfg)
    dialogues: List[str] = []
    for start_centi, end_centi, lines in _build_cue_plan(words, start_off,
                                                         end_off, cfg):
        flat = [word for line in lines for word in line]
        accent = _pick_accent_index(flat) if accents else None
        text = _render_ass_text(lines, accent)
        dialogues.append(
            f"Dialogue: 0,{_ass_timestamp(start_centi)},"
            f"{_ass_timestamp(end_centi)},Default,,0,0,0,,{text}"
        )
    body = "\n".join(dialogues)
    return _ass_header(cfg) + (body + "\n" if body else "")


def build_srt(words: List[TranscriptWord], start_off: float, end_off: float,
              cfg) -> str:
    """Build the plain SRT review copy (same cues as the ASS file)."""
    cues = _build_cue_plan(words, start_off, end_off, cfg)
    blocks: List[str] = []
    for index, (start_centi, end_centi, lines) in enumerate(cues, 1):
        text = " ".join(word for line in lines for word in line)
        blocks.append(
            f"{index}\n"
            f"{_ts(start_centi / CENTI)} --> {_ts(end_centi / CENTI)}\n"
            f"{text}\n"
        )
    return "\n".join(blocks)


def generate(clip_id: str, words: List[TranscriptWord], work_dir: Path,
             start_off: float, end_off: float, cfg) -> Path:
    """Write ``subtitles.ass`` (burn-in) and ``subtitles.srt`` (review).

    Returns the ASS path, which should be passed to the renderer.
    """
    work_dir = Path(work_dir)
    work_dir.mkdir(parents=True, exist_ok=True)
    ass = build_ass(words, start_off, end_off, cfg)
    srt = build_srt(words, start_off, end_off, cfg)

    ass_path = work_dir / "subtitles.ass"
    srt_path = work_dir / "subtitles.srt"
    ass_path.write_text(ass, encoding="utf-8")
    srt_path.write_text(srt, encoding="utf-8")

    log.info("Subtitles %s: %d cue(s) -> %s (+ srt review)",
             clip_id, ass.count("Dialogue:"), ass_path.name)
    return ass_path
